/* ── 문항 → 화면에 낼 문제 ──
   parts: [{ key, label, type: 'one'|'many'|'cut'|'span', options, answer }] */
export function buildQuestion(stage, item, r = Math.random) {
  if (stage === 1) {
    const d = phonemes(item.p) - phonemes(item.w);
    return { stage, item, show: { word: item.w },
      parts: [
        { key: 'pron', label: '표준 발음', type: 'one', options: shuffle([item.p, ...item.x], r).map((p) => `[${p}]`), answer: `[${item.p}]` },
        { key: 'types', label: '일어난 음운 변동 (모두 고르기)', type: 'many', options: TYPES.map((t) => t.name), answer: [...item.t] },
        { key: 'count', label: '음운의 개수는? (표기 → 발음)', type: 'one', options: COUNTS, answer: countLabel(d) }
      ], why: item.why };
  }
  if (stage === 2) {
    return { stage, item, show: { word: item.w },
      parts: [
        { key: 'cut', label: '처음 둘로 나누는 자리', type: 'cut', word: item.w, tail: item.tail || 0, answer: item.cut },
        { key: 'kind', label: '단어의 짜임', type: 'one', options: KINDS, answer: item.k }
      ], why: item.why };
  }
  if (stage === 3) {
    if (item.a) return { stage, item, show: { ant: [item.a, item.b] }, parts: [{ key: 'k', label: '반의 관계의 종류', type: 'one', options: ANT_KINDS, answer: item.k }], why: item.why };
    return { stage, item, show: { poly: item }, parts: [{ key: 'k', label: '두 문장의 ‘' + item.w + '’는 어떤 관계일까요?', type: 'one', options: POLY_KINDS, answer: item.k }], why: item.why };
  }
  if (stage === 4) {
    return { stage, item, show: { pair: [item.a[0], item.b[0]] },
      parts: [
        { key: 'a', label: 'ㄱ의 품사', type: 'one', options: POS, answer: item.a[1] },
        { key: 'b', label: 'ㄴ의 품사', type: 'one', options: POS, answer: item.b[1] }
      ], why: item.why };
  }
  if (stage === 5) {
    const parts = [
      { key: 'span', label: '안긴문장이 든 어절 (모두 누르기)', type: 'span', words: item.s.split(' '), answer: [...item.span] },
      { key: 'k', label: '안긴문장의 종류', type: 'one', options: CLAUSES, answer: item.k }
    ];
    if (item.k === '관형절') parts.push({ key: 'o', label: '관형절에서 빠진 성분', type: 'one', options: OMITS, answer: item.o });
    return { stage, item, show: {}, parts, why: item.why };
  }
  if (stage === 6) {
    if (item.lv) return { stage, item, show: { sent: item.s, cap: '높임 표현 분석' },
      parts: [
        { key: 'subj', label: '주체 높임', type: 'one', options: ['있음', '없음'], answer: item.subj ? '있음' : '없음' },
        { key: 'obj', label: '객체 높임', type: 'one', options: ['있음', '없음'], answer: item.obj ? '있음' : '없음' },
        { key: 'lv', label: '상대 높임 (문장 끝)', type: 'one', options: LEVELS, answer: item.lv }
      ], why: item.why };
    if (item.abs) return { stage, item, show: { sent: item.s, cap: '밑줄 친 말의 시제' },
      parts: [
        { key: 'abs', label: '절대 시제 (말하는 지금 기준)', type: 'one', options: TENSES3, answer: item.abs },
        { key: 'rel', label: '상대 시제 (안은문장의 사건 기준)', type: 'one', options: TENSES3, answer: item.rel }
      ], why: item.why };
    return { stage, item, show: { pair: [item.a[0], item.b[0]], cap: '피동일까, 사동일까?' },
      parts: [
        { key: 'a', label: 'ㄱ', type: 'one', options: VOICES, answer: item.a[1] },
        { key: 'b', label: 'ㄴ', type: 'one', options: VOICES, answer: item.b[1] }
      ], why: item.why };
  }
  const p = PASSAGES[item.p];
  if (item.ask === 't') return { stage, item, show: { old: p, hl: item.hl }, parts: [{ key: 't', label: '밑줄 친 부분을 지금 말로 옮기면?', type: 'one', options: shuffle(item.opts, r), answer: item.opts[0] }], why: item.why };
  return { stage, item, show: { old: p, hl: item.hl }, parts: [{ key: 'f', label: '밑줄 친 말에서 볼 수 있는 특징은?', type: 'one', options: shuffle([item.ans, ...item.not], r).map((k) => F[k]), answer: F[item.ans] }], why: item.why };
}

export const BANKS = { 1: SOUND, 2: WORDS, 3: [...ANTS, ...POLYS], 4: PAIRS, 5: SENTS, 6: [...HONS, ...TENSES, ...VPAIRS], 7: OLDS };
// 한 판(10문제): 문제 묶음을 섞어 겹치지 않게 뽑아요. 3·6단계는 종류가 고르게 섞이게 해요.
// 문항마다 바뀌지 않는 이름 (이미 푼 문제를 기억할 때 씀)
export function itemKey(stage, it) {
  const k = it.w ? it.w + (it.s ? '|' + it.s[1] : '') : it.a ? (Array.isArray(it.a) ? it.a[0] : `${it.a}|${it.b}`) : it.s ? it.s : `${it.p}|${it.ask}|${it.hl}`;
  return `${stage}:${k}`;
}
// 묶음(list)에서 k개 고르기: 아직 안 푼 문제부터. 안 푼 문제가 모자라면 그 묶음은 한 바퀴를 다 돈 것이라
// 기억을 지우고(새 바퀴) 이번 판에 나오지 않은 문제로 채워요. seen은 이미 푼 문제 이름의 Set(바뀜).
function pickFrom(stage, list, k, seen, r) {
  const key = (it) => itemKey(stage, it);
  const fresh = shuffle(list.filter((it) => !seen.has(key(it))), r);
  if (fresh.length >= k) return fresh.slice(0, k);
  const rest = shuffle(list.filter((it) => seen.has(key(it))), r).slice(0, k - fresh.length);
  list.forEach((it) => seen.delete(key(it)));
  return [...fresh, ...rest];
}
// 한 판(10문제): 같은 판 안에서는 겹치지 않고, 묶음을 한 바퀴 다 풀기 전에는 전에 푼 문제가 다시 나오지 않아요.
// 3·6단계는 종류가 고르게 섞이게 종류마다 따로 골라요.
export function makeRound(stage, n = 10, r = Math.random, seen = new Set()) {
  let pool;
  if (stage === 3) pool = [...pickFrom(3, ANTS, 4, seen, r), ...pickFrom(3, POLYS, 6, seen, r)];
  else if (stage === 6) pool = [...pickFrom(6, HONS, 4, seen, r), ...pickFrom(6, TENSES, 3, seen, r), ...pickFrom(6, VPAIRS, 3, seen, r)];
  else pool = pickFrom(stage, BANKS[stage], n, seen, r);
  return shuffle(pool, r).slice(0, n).map((it) => ({ ...buildQuestion(stage, it, r), key: itemKey(stage, it) }));
}
// 채점: 고른 값(sel)과 정답 비교
export function partRight(part, sel) {
  if (part.type === 'many' || part.type === 'span') {
    const a = [...part.answer].map(String).sort().join('|'), b = [...(sel || [])].map(String).sort().join('|');
    return a === b;
  }
  return sel === part.answer;
}
